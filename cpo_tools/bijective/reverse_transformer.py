"""
Reverse transformation: CPO code → custom function declarations.

This module transforms TInCuP-generated CPO + tag_invoke code back to
clean `custom` function declarations for C++29.
"""

from pathlib import Path
from typing import List, Optional

# Handle imports for both module and standalone execution
try:
    from .cpo_parser import parse_cpo_file, CPOFunction
except ImportError:
    import sys
    sys.path.insert(0, str(Path(__file__).parent.parent.parent))
    from cpo_tools.bijective.cpo_parser import parse_cpo_file, CPOFunction


class CPOToCustomTransformer:
    """
    Transform TInCuP-generated CPO code to custom function declarations.

    This is the reverse direction of the bijective transformation.
    """

    def __init__(self):
        self.include_paths: List[str] = []

    def transform_file(
        self,
        input_path: Path,
        output_path: Optional[Path] = None,
        include_paths: List[str] = None
    ) -> str:
        """
        Transform a CPO file to custom declarations.

        Args:
            input_path: Path to CPO header file
            output_path: Optional output file path (if None, return string)
            include_paths: Additional include directories for parsing

        Returns:
            Generated custom declarations as string
        """
        # Parse CPO file
        cpos = parse_cpo_file(str(input_path), include_paths or [])

        # Generate custom declarations
        output = self._generate_header(input_path, cpos)

        # Write or return
        if output_path:
            output_path.write_text(output)
            return output
        else:
            return output

    def _generate_header(self, original_file: Path, cpos: List[CPOFunction]) -> str:
        """Generate the complete header file with custom declarations."""
        lines = []

        # File header
        lines.append("// Custom function declarations")
        lines.append("// Recovered from TInCuP-generated CPO code")
        lines.append(f"// Original file: {original_file.name}")
        lines.append("//")
        lines.append("// This file was generated by TInCuP Bijective Transformer")
        lines.append("// Forward transformation: cpo-bidirectional from-custom")
        lines.append("// Reverse transformation: cpo-bidirectional to-custom")
        lines.append("")
        lines.append("#pragma once")
        lines.append("")

        # Group CPOs by namespace
        by_namespace = self._group_by_namespace(cpos)

        # Generate declarations
        for namespace, funcs in sorted(by_namespace.items()):
            if namespace:
                lines.append(f"namespace {namespace} {{")
                lines.append("")

            for cpo in funcs:
                decl = cpo.to_custom_declaration()
                lines.append(decl)
                lines.append("")

            if namespace:
                lines.append(f"}} // namespace {namespace}")
                lines.append("")

        return "\n".join(lines)

    def _group_by_namespace(self, cpos: List[CPOFunction]) -> dict:
        """Group CPOs by namespace."""
        by_ns = {}
        for cpo in cpos:
            ns = cpo.namespace or ""
            if ns not in by_ns:
                by_ns[ns] = []
            by_ns[ns].append(cpo)
        return by_ns


def transform_cpo_to_custom(
    input_file: str,
    output_file: Optional[str] = None,
    include_paths: List[str] = None
) -> str:
    """
    Convenience function for reverse transformation.

    Args:
        input_file: Path to CPO header file
        output_file: Optional output file path
        include_paths: Additional include directories

    Returns:
        Generated custom declarations

    Example:
        >>> result = transform_cpo_to_custom('generated_cpos.hpp', 'original.hpp')
        >>> print(result)
    """
    transformer = CPOToCustomTransformer()

    input_path = Path(input_file)
    output_path = Path(output_file) if output_file else None

    return transformer.transform_file(input_path, output_path, include_paths)


# Example usage
if __name__ == '__main__':
    import sys

    if len(sys.argv) < 2:
        print("Usage: python reverse_transformer.py <cpo_file.hpp> [output_file.hpp]")
        sys.exit(1)

    input_file = sys.argv[1]
    output_file = sys.argv[2] if len(sys.argv) > 2 else None

    result = transform_cpo_to_custom(input_file, output_file)

    if not output_file:
        print(result)
    else:
        print(f"✓ Generated custom declarations: {output_file}")
