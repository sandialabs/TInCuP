"""
Transform custom function declarations into TInCuP CPO + tag_invoke code.

This module bridges the custom parser with the existing TInCuP code generator.
It takes parsed CustomFunction objects and generates the complete CPO boilerplate.
"""

from typing import List, Optional
from pathlib import Path
from jinja2 import Environment, PackageLoader
import sys

from .custom_parser import CustomFunction
from ..src.process import process_input


class CustomToCPOTransformer:
    """
    Transform custom functions to CPO code using TInCuP generator.

    This class acts as a bridge between:
    1. Custom function parser (regex-based)
    2. TInCuP's existing JSON-based generator
    """

    def __init__(self, enable_metadata: bool = True):
        """
        Initialize transformer.

        Args:
            enable_metadata: If True, embed bijective transformation metadata in output
        """
        self.enable_metadata = enable_metadata
        self.env = Environment(loader=PackageLoader('cpo_tools', 'templates'))

    def transform(self, functions: List[CustomFunction]) -> str:
        """
        Transform a list of custom functions into CPO code.

        Args:
            functions: List of parsed CustomFunction objects

        Returns:
            Generated C++ code containing CPO declarations and tag_invoke stubs
        """
        output_parts = []

        # Header
        output_parts.append(self._generate_header())

        # Process each function
        for func in functions:
            output_parts.append(self._transform_single_function(func))
            output_parts.append("")  # Blank line between functions

        return "\n".join(output_parts)

    def transform_file(self, input_path: Path, output_path: Optional[Path] = None) -> str:
        """
        Transform a file containing custom declarations.

        Args:
            input_path: Path to input file with custom functions
            output_path: Optional path to write output. If None, returns string.

        Returns:
            Generated CPO code
        """
        from .custom_parser import parse_custom_file

        functions = parse_custom_file(str(input_path))

        if not functions:
            raise ValueError(f"No custom functions found in {input_path}")

        output = self.transform(functions)

        if output_path:
            output_path.write_text(output, encoding='utf-8')

        return output

    def _transform_single_function(self, func: CustomFunction) -> str:
        """
        Transform a single custom function to CPO + tag_invoke.

        Args:
            func: CustomFunction object

        Returns:
            Generated C++ code for this function
        """
        parts = []

        # Add metadata comment if enabled
        if self.enable_metadata:
            parts.append(self._generate_metadata_comment(func))

        # Generate CPO declaration using existing TInCuP infrastructure
        cpo_code = self._generate_cpo(func)
        parts.append(cpo_code)

        # Generate tag_invoke stub
        tag_invoke_code = self._generate_tag_invoke_stub(func)
        parts.append(tag_invoke_code)

        return "\n\n".join(parts)

    def _generate_header(self) -> str:
        """Generate file header with includes and metadata."""
        return """// Generated by TInCuP Bijective Transformer
// This file contains CPO declarations transformed from `custom` functions
//
// To regenerate from custom declarations:
//   cpo-bidirectional from-custom input.hpp --output this_file.hpp

#pragma once

#include <tincup/tincup.hpp>

// CPO Declarations
// ===============================================================================
"""

    def _generate_metadata_comment(self, func: CustomFunction) -> str:
        """
        Generate metadata comment for round-trip transformation.

        This enables reverse transformation (CPO → custom).
        """
        lines = [
            "// TINCUP_GENERATED_FROM_CUSTOM",
            f"// TINCUP_ORIGINAL_SIGNATURE: {func}",
            f"// TINCUP_FUNCTION_NAME: {func.function_name}",
        ]

        if func.template_params:
            lines.append(f"// TINCUP_TEMPLATE_PARAMS: {', '.join(func.template_params)}")

        if func.is_noexcept:
            lines.append("// TINCUP_NOEXCEPT: true")

        if func.namespace:
            lines.append(f"// TINCUP_NAMESPACE: {func.namespace}")

        return "\n".join(lines)

    def _generate_cpo(self, func: CustomFunction) -> str:
        """
        Generate CPO declaration using TInCuP's existing generator.

        This reuses the infrastructure from cpo_generator.py.
        """
        # Convert to TInCuP spec format
        spec = func.to_tincup_spec()

        # Use existing TInCuP processing infrastructure
        try:
            # Import here to avoid circular dependency
            from ..src.process import process_input as process_spec
            from ..src.output import wrap_output

            # Process through TInCuP generator
            result = process_spec(spec, from_registry=None, registry_data=None)

            if 'error' in result:
                raise ValueError(f"Error generating CPO for {func.function_name}: {result['error']}")

            # Wrap and return
            cpo_code = wrap_output(result, add_pragma=False, add_include=False)

            return cpo_code

        except Exception as e:
            # Fallback: Generate simple CPO manually
            return self._generate_cpo_fallback(func)

    def _generate_cpo_fallback(self, func: CustomFunction) -> str:
        """
        Fallback CPO generation if main generator fails.

        Generates a minimal but correct CPO structure.
        """
        cpo_name = func.function_name
        args_str = ", ".join(f"typename {p.name.upper()}" for p in func.parameters)
        concept_args = ", ".join(p.name.upper() for p in func.parameters)

        template_header = ""
        if func.template_params or func.parameters:
            # Need template for generic operator()
            template_header = f"  template<{args_str}>\n"

        return f"""inline constexpr struct {cpo_name}_ftor final : tincup::cpo_base<{cpo_name}_ftor> {{
  TINCUP_CPO_TAG("{cpo_name}")
  inline static constexpr bool is_variadic = false;
  using tincup::cpo_base<{cpo_name}_ftor>::operator();

{template_header}  constexpr auto operator()({self._format_params_for_operator(func.parameters)}) const
    noexcept(tincup::nothrow_invocable_c<{cpo_name}_ftor, {concept_args}>)
    -> tincup::invocable_t<{cpo_name}_ftor, {concept_args}> {{
    return tincup::tag_invoke_cpo(*this, {", ".join(p.name for p in func.parameters)});
  }}
}} {cpo_name};"""

    def _format_params_for_operator(self, parameters: List) -> str:
        """Format parameters for CPO operator()."""
        if not parameters:
            return ""

        # Use generic forwarding references
        return ", ".join(f"{p.name.upper()}&& {p.name}" for p in parameters)

    def _generate_tag_invoke_stub(self, func: CustomFunction) -> str:
        """
        Generate tag_invoke stub declaration.

        This creates a stub that user needs to implement.
        """
        lines = []

        # Template header
        if func.template_params:
            lines.append(f"template<{', '.join(func.template_params)}>")

        # tag_invoke signature
        params = [f"{func.function_name}_ftor"]  # CPO tag as first param
        params.extend(f"{p.type_str} {p.name}" for p in func.parameters)

        noexcept_str = " noexcept" if func.is_noexcept else ""

        signature = f"{func.return_type} tag_invoke({', '.join(params)}){noexcept_str}"

        # Add stub body
        lines.append(f"{signature} {{")
        lines.append("  // TODO: Implement")

        if func.return_type != "void":
            # Add placeholder return for non-void
            lines.append(f"  return {{}};  // Replace with actual implementation")

        lines.append("}")

        return "\n".join(lines)


def transform_custom_to_cpo(input_path: str,
                            output_path: Optional[str] = None,
                            enable_metadata: bool = True) -> str:
    """
    Convenience function to transform custom declarations to CPO code.

    Args:
        input_path: Path to file with custom function declarations
        output_path: Optional output path. If None, returns string.
        enable_metadata: Include metadata for reverse transformation

    Returns:
        Generated CPO code

    Example:
        >>> result = transform_custom_to_cpo('my_lib.hpp', 'my_lib_cpo.hpp')
        >>> print(f"Generated CPO code in my_lib_cpo.hpp")
    """
    transformer = CustomToCPOTransformer(enable_metadata=enable_metadata)

    output_path_obj = Path(output_path) if output_path else None

    return transformer.transform_file(Path(input_path), output_path_obj)


# Example usage
if __name__ == '__main__':
    import tempfile

    # Example custom code
    example_code = '''
template<typename T>
custom void serialize(const T& obj, std::ostream& os);

custom int compute(double x) noexcept;
'''

    # Write to temp file
    with tempfile.NamedTemporaryFile(mode='w', suffix='.hpp', delete=False) as f:
        f.write(example_code)
        temp_path = f.name

    try:
        # Transform
        result = transform_custom_to_cpo(temp_path)
        print("Generated CPO code:")
        print("=" * 80)
        print(result)
    finally:
        # Cleanup
        Path(temp_path).unlink()
